// THIRD_PARTY_LICENSES.md: the license text of every crate linked into the
// `diodecam` sender, as the crate ships it (copyright lines included). The
// release archive carries this file next to the binary; web/licenses.html
// lists the same crates. Regenerate when Cargo.lock changes.
//
// When a crate offers a choice, DiodeCam takes Apache-2.0 where offered, else MIT
// (the rule web/licenses.html states), and includes that text.
//
// usage: node tools/third-party-licenses.ts   (needs cargo and network: it runs `cargo vendor`)

import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { cargoEnv } from './cargo.ts'

const TARGETS = ['x86_64-unknown-linux-musl', 'aarch64-unknown-linux-musl', 'aarch64-apple-darwin', 'x86_64-apple-darwin']

/** `name version` of every crate in the sender's normal dependency tree on any release target. */
function senderCrates(): Map<string, string> {
  const crates = new Map<string, string>()
  for (const target of TARGETS) {
    const run = spawnSync('cargo', ['tree', '-q', '-p', 'diodecam-cli', '-e', 'normal', '--prefix', 'none', '--target', target], { encoding: 'utf8', env: cargoEnv() })
    if (run.status !== 0) throw new Error(`cargo tree --target ${target} failed: ${run.stderr}`)
    for (const line of run.stdout.split('\n')) {
      const m = /^(\S+) v(\S+)/.exec(line.trim())
      if (m && !m[1]!.startsWith('diodecam')) crates.set(m[1]!, m[2]!)
    }
  }
  return crates
}

/** The license file to include for a crate: Apache-2.0 where offered, else MIT, else whatever it ships. */
function pickLicense(dir: string, expr: string): { chosen: string; file: string } {
  // Files at the crate root, plus a REUSE-style LICENSES/ folder (crc-catalog).
  const files = readdirSync(dir).filter((f) => /^(LICEN[CS]E|COPYING|NOTICE)/i.test(f) && statSync(join(dir, f)).isFile())
  const reuse = join(dir, 'LICENSES')
  if (existsSync(reuse)) for (const f of readdirSync(reuse)) files.push(join('LICENSES', f))
  const find = (re: RegExp) => files.find((f) => re.test(f))
  const options = expr.split(/\s+OR\s+|\//).map((s) => s.trim())
  if (options.some((o) => o === 'Apache-2.0')) {
    const f = find(/apache(?!.*llvm)/i) ?? (options.length === 1 ? find(/^LICENSE(\.md|\.txt)?$/i) : undefined)
    if (f) return { chosen: 'Apache-2.0', file: f }
  }
  if (options.some((o) => o === 'MIT')) {
    const f = find(/mit/i) ?? (options.length === 1 ? find(/^LICENSE(\.md|\.txt)?$/i) : undefined)
    if (f) return { chosen: 'MIT', file: f }
  }
  const f = files[0]
  if (!f) throw new Error(`${dir}: no license file for "${expr}"`)
  return { chosen: options[0] ?? expr, file: f }
}

const crates = senderCrates()
const vendor = mkdtempSync(join(tmpdir(), 'diodecam-vendor-'))
try {
  const run = spawnSync('cargo', ['vendor', '-q', '--locked', vendor], { stdio: ['ignore', 'ignore', 'inherit'], env: cargoEnv() })
  if (run.status !== 0) throw new Error('cargo vendor failed')
  const sections: string[] = []
  const table: string[] = []
  for (const [name, version] of [...crates].sort()) {
    const dir = [join(vendor, name), join(vendor, `${name}-${version}`)].find((d) => existsSync(join(d, 'Cargo.toml')))
    if (!dir) throw new Error(`${name} ${version}: not in the vendored sources`)
    const toml = readFileSync(join(dir, 'Cargo.toml'), 'utf8')
    const expr = /^license\s*=\s*"([^"]+)"/m.exec(toml)?.[1] ?? 'unknown'
    const { chosen, file } = pickLicense(dir, expr)
    const text = readFileSync(join(dir, file), 'utf8').trim()
    table.push(`| ${name} | ${version} | ${expr} | ${chosen} |`)
    sections.push(`## ${name} ${version}\n\nLicense: ${expr} — used under ${chosen} (${file})\n\n\`\`\`\n${text}\n\`\`\``)
  }
  const doc = `# Third-party licenses

The \`diodecam\` sender statically links the Rust crates below. The web receiver's
WebAssembly module is built from a subset of them (raptorq, reed-solomon, crc,
sha2, flate2 and their dependencies). DiodeCam itself is Apache-2.0 (LICENSE).

Generated by \`node tools/third-party-licenses.ts\` from Cargo.lock; each text is
the file the crate ships. Where a crate offers a choice, DiodeCam uses Apache-2.0
if offered, else MIT.

| Crate | Version | Offered | Used under |
|---|---|---|---|
${table.join('\n')}

${sections.join('\n\n')}
`
  writeFileSync('THIRD_PARTY_LICENSES.md', doc)
  console.log(`THIRD_PARTY_LICENSES.md: ${crates.size} crates, ${(doc.length / 1024).toFixed(0)} KiB`)
} finally {
  rmSync(vendor, { recursive: true, force: true })
}
